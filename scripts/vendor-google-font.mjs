#!/usr/bin/env node
/**
 * Vendor a Google Fonts family into `resources/fonts/<normalized>/` as the
 * `unicode-range`-sliced woff2 files Google serves to Chromium, so the app can
 * self-host CJK/Thai coverage without shipping a multi-megabyte monolith.
 *
 *   node scripts/vendor-google-font.mjs "Noto Sans KR" --axis "wght@100..900"
 *
 * The directory and CSS names follow `injectFontCSS` in
 * react/src/helper/customThemeConfig.ts (lowercase, spaces -> hyphens), so the
 * family only needs to be listed in resources/theme.json `fontFamily` to load.
 * Re-running replaces the previously vendored slices and CSS; other files in
 * the directory (e.g. a hand-placed license) are left alone.
 */
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const CHROME_UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36";
const FONTS_DIR = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../resources/fonts",
);

const args = process.argv.slice(2);
const family = args.find((a) => !a.startsWith("--"));
const axisIdx = args.indexOf("--axis");
const axis = axisIdx >= 0 ? args[axisIdx + 1] : undefined;
if (!family) {
  console.error(
    'usage: node scripts/vendor-google-font.mjs "<Family Name>" [--axis "wght@100..900"]',
  );
  process.exit(2);
}

const normalized = family.toLowerCase().replace(/\s+/g, "-");
const dir = path.join(FONTS_DIR, normalized);
const familyParam =
  encodeURIComponent(family).replace(/%20/g, "+") + (axis ? `:${axis}` : "");
const cssUrl = `https://fonts.googleapis.com/css2?family=${familyParam}&display=swap`;

async function fetchOk(url, init) {
  const res = await fetch(url, init);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res;
}

const css = await (
  await fetchOk(cssUrl, { headers: { "User-Agent": CHROME_UA } })
).text();
const blocks = css.match(/(\/\*[^*]*\*\/\s*)?@font-face\s*\{[^}]*\}/g) ?? [];
if (blocks.length === 0) throw new Error(`no @font-face blocks in ${cssUrl}`);

await mkdir(dir, { recursive: true });
for (const entry of await readdir(dir)) {
  if (entry.endsWith(".woff2") || entry === `${normalized}.css`) {
    await rm(path.join(dir, entry));
  }
}

const out = [];
let version = "v0";
for (const [i, block] of blocks.entries()) {
  const src = block.match(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/);
  if (!src) throw new Error(`block ${i} has no gstatic url:\n${block}`);
  version = src[1].match(/\/(v\d+)\//)?.[1] ?? version;
  const file = `${normalized}-${version}-${i}.woff2`;
  const bytes = await (await fetchOk(src[1])).arrayBuffer();
  await writeFile(path.join(dir, file), Buffer.from(bytes));
  out.push(block.replace(src[0], `url('./${file}')`));
}

const header = `/* Generated by scripts/vendor-google-font.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
   Source: ${cssUrl}
   ${blocks.length} unicode-range slices, ${version}. Re-run the script to update. */\n\n`;
await writeFile(
  path.join(dir, `${normalized}.css`),
  header + out.join("\n") + "\n",
);
console.log(
  `${family}: ${blocks.length} slices (${version}) -> ${path.relative(process.cwd(), dir)}`,
);
